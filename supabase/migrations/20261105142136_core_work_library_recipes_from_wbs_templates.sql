-- Appends a kit part's missing activities to a recipe, chained FS after its last step.
create or replace function pg_temp.wl_append_gap(p_template uuid, p_kit text, p_part text) returns int language plpgsql as $$
declare
  g record;
  v_seq int;
  v_prev uuid;
  v_new uuid;
  v_master uuid;
  v_n int := 0;
begin
  select coalesce(max(seq), 0) into v_seq from public.plan_act_template_items where template_id = p_template;
  select id into v_prev from public.plan_act_template_items where template_id = p_template order by seq desc limit 1;
  for g in select * from _gap where kit_code = p_kit and part = p_part order by ord loop
    select m.id into v_master from public.plan_act_masters m
     where m.code = g.master_code and m.status not in ('superseded', 'archived') order by m.version desc limit 1;
    if v_master is null then continue; end if;
    if exists (select 1 from public.plan_act_template_items i join public.plan_act_masters mm on mm.id = i.master_id
                where i.template_id = p_template and mm.code = g.master_code) then continue; end if;
    v_seq := v_seq + 1;
    insert into public.plan_act_template_items (template_id, seq, master_id, scope, duration_days_override, note)
    values (p_template, v_seq, v_master, 'floor', g.dur, 'From the WBS template floor block (2026-11-05 alignment)')
    returning id into v_new;
    if v_prev is not null then
      insert into public.plan_act_template_dependencies (template_id, predecessor_item_id, successor_item_id, relation, lag_days, is_optional)
      values (p_template, v_prev, v_new, 'fs', 0, false);
    end if;
    v_prev := v_new;
    v_n := v_n + 1;
  end loop;
  return v_n;
end $$;

do $$
declare
  g record;
  k record;
  ki record;
  b record;
  v_short text;
  v_code text;
  v_id uuid;
  v_new uuid;
  v_dom uuid;
  it record;
  v_map jsonb;
begin
  for g in select distinct kit_code, part from _gap order by 1, 2 loop
    select * into k from public.plan_act_kits where code = g.kit_code and status not in ('superseded', 'archived') order by version desc limit 1;
    if k.id is null then continue; end if;
    v_short := regexp_replace(k.code, '^KIT-', '');

    if exists (select 1 from public.plan_act_kit_items where kit_id = k.id and part = g.part) then
      for ki in select * from public.plan_act_kit_items where kit_id = k.id and part = g.part order by sort_order loop
        select * into b from public.plan_act_templates where code = ki.template_code and status not in ('superseded', 'archived') order by version desc limit 1;
        if b.id is null then continue; end if;
        if (b.code like '%-' || v_short || '-' || upper(g.part) or b.code = 'TPL-' || v_short || '-' || upper(g.part) || '-001')
           and b.status = 'draft' then
          v_id := b.id;                                   -- already this kit part's copy
        else
          v_code := b.code || '-' || v_short || '-' || upper(g.part);
          select id into v_id from public.plan_act_templates where code = v_code and status = 'draft' order by version desc limit 1;
          if v_id is null then
            insert into public.plan_act_templates (code, name, description, domain_id, status, version, applies_to_level_types, owner,
                   inter_level_from_seq, inter_level_to_seq, inter_level_relation, inter_level_lag_days, sectors, building_types)
            values (v_code, b.name || ' – ' || k.name || ' (' || g.part || ')',
                    trim(coalesce(b.description, '') || ' Copy of ' || b.code || ' for kit ' || k.code || ', with the WBS template activities the base recipe lacks (2026-11-05).'),
                    b.domain_id, 'draft', 1, b.applies_to_level_types, b.owner,
                    b.inter_level_from_seq, b.inter_level_to_seq, b.inter_level_relation, b.inter_level_lag_days, b.sectors, b.building_types)
            returning id into v_id;
            v_map := '{}'::jsonb;
            for it in select * from public.plan_act_template_items where template_id = b.id order by seq loop
              insert into public.plan_act_template_items (template_id, seq, master_id, scope, method_id, norm_id, duration_days_override, is_milestone, note, crews)
              values (v_id, it.seq, it.master_id, it.scope, it.method_id, it.norm_id, it.duration_days_override, it.is_milestone, it.note, it.crews)
              returning id into v_new;
              v_map := v_map || jsonb_build_object(it.id::text, v_new);
            end loop;
            insert into public.plan_act_template_dependencies (template_id, predecessor_item_id, successor_item_id, relation, lag_days, is_optional)
            select v_id, (v_map ->> d.predecessor_item_id::text)::uuid, (v_map ->> d.successor_item_id::text)::uuid, d.relation, d.lag_days, d.is_optional
              from public.plan_act_template_dependencies d where d.template_id = b.id;
            insert into public.plan_act_applicability (target_type, target_id, attribute, operator, values)
            select 'template', v_id, a.attribute, a.operator, a.values
              from public.plan_act_applicability a where a.target_type = 'template' and a.target_id = b.id;
          end if;
          update public.plan_act_kit_items set template_code = v_code where id = ki.id;
        end if;
        perform pg_temp.wl_append_gap(v_id, g.kit_code, g.part);
      end loop;
    else
      v_code := 'TPL-' || v_short || '-' || upper(g.part) || '-001';
      select id into v_id from public.plan_act_templates where code = v_code order by version desc limit 1;
      if v_id is null then
        select t.domain_id into v_dom from public.plan_act_templates t join public.plan_act_kit_items x on x.template_code = t.code
         where x.kit_id = k.id and t.domain_id is not null limit 1;
        insert into public.plan_act_templates (code, name, description, domain_id, status, version, applies_to_level_types, owner, sectors, building_types)
        values (v_code, k.name || ' – ' || initcap(g.part) || ' (from WBS templates)',
                'Recipe for the ' || g.part || ' floor block of the ' || k.code || ' WBS templates (2026-11-05 alignment).',
                v_dom, 'draft', 1, array[g.part], 'Planning Standards', k.sectors, k.building_types)
        returning id into v_id;
      end if;
      insert into public.plan_act_kit_items (kit_id, part, template_code, sort_order)
      select k.id, g.part, v_code, coalesce((select max(sort_order) from public.plan_act_kit_items where kit_id = k.id), 0) + 10
       where not exists (select 1 from public.plan_act_kit_items where kit_id = k.id and part = g.part and template_code = v_code);
      perform pg_temp.wl_append_gap(v_id, g.kit_code, g.part);
    end if;
  end loop;
end $$;
