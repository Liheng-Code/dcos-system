create or replace function pg_temp.link_ins_tasks(arr jsonb, is_ins boolean) returns jsonb
language sql stable as $f$
  select coalesce(jsonb_agg(
           case when coalesce(x->>'master_code', '') = '' and m.master_code is not null and (is_ins or not m.institutional_only)
                then x || jsonb_build_object('master_code', m.master_code) else x end order by o), '[]'::jsonb)
  from jsonb_array_elements(coalesce(arr, '[]'::jsonb)) with ordinality e(x, o)
  left join _ins_master_map m on lower(m.task_name) = lower(btrim(x->>'task_name'))
$f$;

update public.wbs_templates w
   set content = jsonb_set(w.content, '{floor_blocks}',
         coalesce((select jsonb_object_agg(b.key, b.value || jsonb_build_object('tasks', pg_temp.link_ins_tasks(b.value->'tasks', w.template_category = 'institutional')))
                     from jsonb_each(coalesce(w.content->'floor_blocks', '{}'::jsonb)) b), '{}'::jsonb))
 where w.template_category is distinct from 'infrastructure' and jsonb_typeof(w.content->'floor_blocks') = 'object';
