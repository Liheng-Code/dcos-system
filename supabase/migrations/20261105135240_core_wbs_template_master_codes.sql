         select coalesce(jsonb_agg(case when l.master_code is not null and coalesce(t->>'master_code', '') = ''
                                        then t || jsonb_build_object('master_code', l.master_code) else t end order by o), '[]'::jsonb)
           from jsonb_array_elements(w.content->'sections'->'tasks') with ordinality e(t, o)
           left join _wl_links l on l.template_name = w.template_name and l.area = 'section' and l.task_key = t->>'key'))
